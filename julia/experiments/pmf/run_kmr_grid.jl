"""
    run_kmr_grid.jl

King–McKinley-rule (KMR) comparison grid: steady simple shear (PMF r = 1,
fixed-Wi sweep) and steady planar extension (STYEXT α = (1, −1, 0), PAC over
all branches) for 18 cases. Spec: docs/logs/aru-to-ko/2026-10-16_kmr-comparison-grid.md.

Grid (common: N_K = 5000, h*_K = 0.25, non-draining, RP drag scheme, 4000-pt drag LUT)
  Block A : constant drag, φ = 0, fixed Rouse spectrum (p⁻²)
  Block B : C2D2 drag,     φ = 0, blob spectrum
  Block C : C2D2 drag,     φ = 1, blob spectrum
  × N_m ∈ {1, 10, 100} × {Hookean, FENE-PM (Q∞² = N_K/N_m)}

Usage (repo root):
  julia --project=julia julia/experiments/pmf/run_kmr_grid.jl --gen-tomls          # (re)write inputs/kmr_grid/*.toml
  julia --project=julia julia/experiments/pmf/run_kmr_grid.jl [--only SUBSTR] [--skip-shear] [--skip-planar] [--verbose]

Outputs (gitignored): julia/experiments/pmf/outputs/kmr_grid/
  <case>_shear.csv        fixed-Wi sweep, λ₀γ̇ = 1e-2 … 1e4, 10/decade (both Wi columns, flow-frame τ, η_p, Ψ₁, Ψ₂, Y, X)
  <case>_shear_modes.csv  per-mode A, B, C, D, flow-frame M, orientation angle χ_p (deg), θ_p, σ_p, f_p
  <case>_shear_pac.csv    (only if the fixed-Wi sweep did not converge everywhere) PAC trace of the shear manifold
  <case>_planar.csv       PAC from equilibrium to Y_stop or X_stop (FENE closure X → 0.999 Q∞²), all branches; `branch` (coiled/retrograde/stretched by
                          fold count along the path) and `stable` (dWi/ds > 0) flags — fold-based, not a
                          linearised stability analysis
  kmr_grid_manifest.csv   one row per case: parameters, η₀, Ψ₁,₀, λ_Ψη = Ψ₁,₀/(2η₀), run status, wall time

Conventions: Wi = λ₀ × principal strain rate (report appendix); Wi_shear = 2·Wi = λ₀γ̇.
Stress τ/(c kBT) = −Σ(3 f_p M_p − I) (Stress.jl sign); η_p, Ψ₁ positive. X = mean_p tr M_p.
"""

