function gen_tomls()
    mkpath(_INPUTS)
    for c in grid_cases()
        common = replace(_toml_common(c), r"^    "m => "")
        write(joinpath(_INPUTS, "$(c.id)_shear.toml"),
              "[run]\nlabel = \"$(c.id)_shear\"\n\n" * common *
              "\n[flow]\nkind          = \"pmf\"\nr             = 1.0\nWi_convention = \"shear\"   # [sweep] Wi below are lambda0*gammadot\n" *
              "\n[sweep]\nWi_min       = $(SHEAR_WI[1])\nWi_max       = $(SHEAR_WI[2])\nn_per_decade = $(SHEAR_WI[3])\n")
        write(joinpath(_INPUTS, "$(c.id)_planar.toml"),
              "[run]\nlabel = \"$(c.id)_planar\"\n\n" * common *
              "\n[flow]\nkind   = \"styext\"\nalphas = [1.0, -1.0, 0.0]\n")
    end
    println("wrote $(2 * length(grid_cases())) TOMLs to $_INPUTS")
end

# ── Helpers ───────────────────────────────────────────────────────────────────

_f(x) = isfinite(x) ? @sprintf("%.12g", x) : string(x)

"""Fold-based branch labels along a PAC path from the sequence of Wi values."""
function branch_flags(Wis::Vector{Float64})
    n = length(Wis)
    branch = fill("coiled", n); stable = trues(n); folds = 0; prev = 0.0
    for k in 2:n
        d = Wis[k] - Wis[k-1]
        abs(d) <= 1e-9 * max(abs(Wis[k]), 1e-300) && (d = 0.0)     # ignore roundoff-level reversals
        if k > 2 && d != 0.0 && prev != 0.0 && sign(d) != sign(prev)
            folds += 1
        end
        d != 0.0 && (prev = d)
        stable[k] = d > 0.0
        branch[k] = folds == 0 ? "coiled" : folds == 1 ? "retrograde" : folds == 2 ? "stretched" : "fold$(folds)"
    end
    return branch, stable, folds
end

function _mean_trace(ctx, X, Y, mu)
    r = eval_modal_tensors(ctx, X, Y, mu)
    if ctx.flow isa PlanarMixedFlow
        A, B, C, D = r.M
        return sum(A .+ B .+ D) / ctx.Nm, r
    else
        return sum(r.M) / ctx.Nm, r
    end
end

# ── Writers ───────────────────────────────────────────────────────────────────

function write_shear_csv(path, ctx, traj)
    open(path, "w") do io
        println(io, "idx,Wi,Wi_shear,Y,X,eta_p,Psi1,Psi2,tau_xx,tau_yy,tau_zz,tau_xy,tau_11,tau_22,tau_12,Wi_pole,newton_iters,status")
        for p in traj
            o = p.obs; Xm, _ = _mean_trace(ctx, p.X, p.Y, p.mu)
            half = 0.5 * (o.tau_xx + o.tau_yy)
            println(io, join([p.idx, _f(o.Wi), _f(wi_shear(o.Wi)), _f(o.E2), _f(Xm),
                              _f(o.eta_p), _f(o.Psi1), _f(o.Psi2),
                              _f(o.tau_xx), _f(o.tau_yy), _f(o.tau_zz), _f(o.tau_xy),
                              _f(half + o.tau_xy), _f(half - o.tau_xy), _f(0.5 * (o.tau_yy - o.tau_xx)),
                              _f(p.Wi_pole), p.newton_iters, p.status_str], ","))
        end
    end
end

function write_shear_modes_csv(path, ctx, traj)
    open(path, "w") do io
        println(io, "idx,Wi,Wi_shear,p,theta_p,sigma_p,f_p,A,B,C,D,M_xx,M_yy,M_xy,trM_p,chi_p_deg")
        for p in traj
            _, r = _mean_trace(ctx, p.X, p.Y, p.mu)
            A, B, C, D = r.M
            for q in 1:ctx.Nm
                Mxx = 0.5 * (A[q] + B[q]) - C[q]
                Myy = 0.5 * (A[q] + B[q]) + C[q]
                Mxy = 0.5 * (A[q] - B[q])
                chi = 0.5 * atand(2 * Mxy, Mxx - Myy)     # principal-axis angle from the flow direction
                println(io, join([p.idx, _f(r.Wi), _f(wi_shear(r.Wi)), q,
                                  _f(r.theta_p[q]), _f(r.sigma_p[q]), _f(r.fp[q]),
                                  _f(A[q]), _f(B[q]), _f(C[q]), _f(D[q]),
                                  _f(Mxx), _f(Myy), _f(Mxy), _f(A[q] + B[q] + D[q]), _f(chi)], ","))
            end
        end
    end
end

function write_planar_csv(path, ctx, traj)
    Wis = [p.obs.Wi for p in traj]
    branch, stable, folds = branch_flags(Wis)
    open(path, "w") do io
        println(io, "idx,Wi,Y,X,tau_11,tau_22,tau_33,etaP1,etaP2,Wi_pole,mu,newton_iters,ds,FY_rel,status,branch,stable")
        for (k, p) in enumerate(traj)
            o = p.obs; Xm, _ = _mean_trace(ctx, p.X, p.Y, p.mu)
            println(io, join([p.idx, _f(o.Wi), _f(o.E2), _f(Xm),
                              _f(o.tau_xx), _f(o.tau_yy), _f(o.tau_zz), _f(o.etaE1), _f(o.etaE2),
                              _f(p.Wi_pole), _f(p.mu), p.newton_iters, _f(p.ds), _f(p.FY_rel), p.status_str,
                              branch[k], stable[k] ? 1 : 0], ","))
        end
    end
    return folds
end

const MANIFEST_HDR = "case_id,block,drag,phi,Nm,spectrum,force,NK,hK_star,drag_lut_n_points,eta0,Psi10,lambda_Psi_eta," *
                     "shear_status,shear_npts,shear_Wi_shear_max,shear_Y_max,shear_X_frac_max,shear_pac_written,wall_shear_s," *
                     "planar_status,planar_npts,planar_reason,planar_Wi_end,planar_Y_end,planar_Wi_max,planar_X_frac_end,planar_n_folds,wall_planar_s"

"""Merge rows (keyed by case_id) into an existing manifest so partial reruns keep other cases."""
function write_manifest(path, rows)
    existing = Dict{String, String}()
    if isfile(path)
        for l in readlines(path)[2:end]
            isempty(strip(l)) && continue
            existing[first(split(l, ','))] = l
        end
    end
    for r in rows; existing[first(split(r, ','))] = r; end
    order = [c.id for c in grid_cases()]
    open(path, "w") do io
        println(io, MANIFEST_HDR)
        for id in order; haskey(existing, id) && println(io, existing[id]); end
        for (id, l) in existing; id in order || println(io, l); end
    end
end

# ── Runners ───────────────────────────────────────────────────────────────────

function run_shear(c::KmrCase; verbose = false)
    params, ctx, so, mo = load_styext_context(joinpath(_INPUTS, "$(c.id)_shear.toml"))
    eta0, Psi10 = linear_limit_shear(ctx)
    t0 = time()
    traj = sweep_fixed_Wi(ctx, params.Wi_sweep, so; verbose = verbose, stop_on_fail = false, X_stop = mo.X_stop)
    wall = time() - t0
    write_shear_csv(joinpath(_OUT, "$(c.id)_shear.csv"), ctx, traj)
    write_shear_modes_csv(joinpath(_OUT, "$(c.id)_shear_modes.csv"), ctx, traj)
    n_ok = count(p -> p.status_str in ("eq", "FWi-cnv"), traj)
    n_fail = count(p -> p.status_str == "FWi-fail", traj)
    stopped_Y = any(p -> p.status_str == "Y_stop", traj)
    stopped_X = any(p -> p.status_str == "X_stop", traj)
    status = n_fail == 0 ? (stopped_Y ? "ok_Ystop" : stopped_X ? "ok_Xstop" : "ok") : "partial($(n_fail) fail)"
    pac_written = false
    if n_fail > 0
        # fold or branch change at fixed Wi: trace the shear manifold with PAC instead
        mo2 = ManifoldOpts(ds0 = mo.ds0, ds_min = mo.ds_min, ds_max = mo.ds_max, max_steps = mo.max_steps,
                           Wi_max = SHEAR_WI[2] / 2, tol_FY_rel_hard = mo.tol_FY_rel_hard,
                           target_newton = mo.target_newton, target_rho = mo.target_rho, verbose = false,
                           X_stop = mo.X_stop)
        tp = build_manifold(ctx, so, mo2)
        write_shear_csv(joinpath(_OUT, "$(c.id)_shear_pac.csv"), ctx, tp)
        pac_written = true
        # If the PAC trace of the shear manifold is monotone in Wi and ends at the
        # Y cap (E = E∞ = √N_K, where the C2D2 drag is clamped), the fixed-Wi
        # failures are the model's Y domain ending, not a solver problem.
        Wp = [q.obs.Wi for q in tp]
        monotone = all(diff(Wp) .>= -1e-9 .* max.(abs.(Wp[2:end]), 1e-300))
        if monotone && tp[end].Y >= ctx.Ymax * (1 - 1e-6)
            status = @sprintf("ok_Ycap_PAC(λγ̇_cap=%.4g)", wi_shear(tp[end].obs.Wi))
        end
    end
    ok = filter(p -> p.status_str in ("eq", "FWi-cnv", "X_stop"), traj)
    Wi_s_max = isempty(ok) ? NaN : wi_shear(maximum(p.obs.Wi for p in ok))
    Y_max    = isempty(ok) ? NaN : maximum(p.Y for p in ok)
    X_frac   = isempty(ok) ? NaN : maximum(_mean_trace(ctx, p.X, p.Y, p.mu)[1] for p in ok) / params.Qinf_sq
    @printf("    shear : %-16s %3d/%3d pts  λγ̇_max=%.3g  Y_max=%.5g  X/Q∞²=%.4f  η₀=%.6g  Ψ₁₀=%.6g  (%.1fs)%s\n",
            status, n_ok, length(traj), Wi_s_max, Y_max, X_frac, eta0, Psi10, wall, pac_written ? "  [+PAC fallback]" : "")
    return (eta0 = eta0, Psi10 = Psi10, status = status, npts = length(traj), Wi_s_max = Wi_s_max,
            Y_max = Y_max, X_frac = X_frac, pac = pac_written, wall = wall)
end

function run_planar(c::KmrCase; verbose = false)
    params, ctx, so, mo = load_styext_context(joinpath(_INPUTS, "$(c.id)_planar.toml"))
    mo2 = ManifoldOpts(ds0 = mo.ds0, ds_min = mo.ds_min, ds_max = mo.ds_max, max_steps = mo.max_steps,
                       Wi_max = mo.Wi_max, tol_FY_rel_hard = mo.tol_FY_rel_hard,
                       target_newton = mo.target_newton, target_rho = mo.target_rho, verbose = verbose,
                       X_stop = mo.X_stop)
    t0 = time()
    traj, reason = build_manifold(ctx, so, mo2; return_reason = true)
    wall = time() - t0
    folds = write_planar_csv(joinpath(_OUT, "$(c.id)_planar.csv"), ctx, traj)
    Wis = [p.obs.Wi for p in traj]
    status = reason in ("Y_stop", "X_stop") ? "ok_$(reason)" : "ended($(reason))"
    X_frac = _mean_trace(ctx, traj[end].X, traj[end].Y, traj[end].mu)[1] / params.Qinf_sq
    @printf("    planar: %-16s %5d pts  Wi_end=%.5g  Wi_max=%.5g  Y_end=%.5g  X/Q∞²=%.4f  folds=%d  (%.1fs)\n",
            status, length(traj), Wis[end], maximum(Wis), traj[end].Y, X_frac, folds, wall)
    return (status = status, npts = length(traj), reason = reason, Wi_end = Wis[end], Y_end = traj[end].Y,
            Wi_max = maximum(Wis), X_frac = X_frac, folds = folds, wall = wall)
end

function main()
    args = copy(ARGS)
    if "--gen-tomls" in args
        gen_tomls(); return
    end
    verbose     = "--verbose" in args
    skip_shear  = "--skip-shear" in args
    skip_planar = "--skip-planar" in args
    only = let i = findfirst(==("--only"), args); i === nothing ? "" : args[i+1] end

    cases = filter(c -> occursin(only, c.id), grid_cases())
    isdir(_INPUTS) || gen_tomls()
    mkpath(_OUT)
    manifest_path = joinpath(_OUT, "kmr_grid_manifest.csv")
    rows = String[]
    println("=== KMR comparison grid: $(length(cases)) case(s)  ($(Dates.format(now(), "yyyy-mm-dd HH:MM"))) ===")
    for c in cases
        println("$(c.id)")
        sh = pl = nothing
        try
            skip_shear  || (sh = run_shear(c; verbose = verbose))
        catch e
            @warn "shear run failed: $(c.id)" exception = (e, catch_backtrace())
        end
        try
            skip_planar || (pl = run_planar(c; verbose = verbose))
        catch e
            @warn "planar run failed: $(c.id)" exception = (e, catch_backtrace())
        end
        eta0, Psi10 = sh === nothing ? (NaN, NaN) : (sh.eta0, sh.Psi10)
        push!(rows, join([c.id, c.block, c.drag, _f(c.phi), c.Nm, c.spectrum, c.force, NK, _f(HK), LUT_N,
                          _f(eta0), _f(Psi10), _f(Psi10 / (2eta0)),
                          sh === nothing ? "not_run" : sh.status, sh === nothing ? 0 : sh.npts,
                          sh === nothing ? "NaN" : _f(sh.Wi_s_max), sh === nothing ? "NaN" : _f(sh.Y_max),
                          sh === nothing ? "NaN" : _f(sh.X_frac),
                          sh === nothing ? 0 : (sh.pac ? 1 : 0), sh === nothing ? "NaN" : _f(sh.wall),
                          pl === nothing ? "not_run" : pl.status, pl === nothing ? 0 : pl.npts,
                          pl === nothing ? "" : pl.reason, pl === nothing ? "NaN" : _f(pl.Wi_end),
                          pl === nothing ? "NaN" : _f(pl.Y_end), pl === nothing ? "NaN" : _f(pl.Wi_max),
                          pl === nothing ? "NaN" : _f(pl.X_frac),
                          pl === nothing ? -1 : pl.folds, pl === nothing ? "NaN" : _f(pl.wall)], ","))
        write_manifest(manifest_path, rows)      # rewritten after every case
    end
    println("manifest -> $manifest_path")
end

main()
