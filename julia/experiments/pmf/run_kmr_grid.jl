# ── Grid definition ───────────────────────────────────────────────────────────

struct KmrCase
    id       :: String
    block    :: String
    drag     :: String      # "constant" | "c2d2"
    phi      :: Float64
    Nm       :: Int
    spectrum :: String      # "rouse-scaling" | "blob"
    force    :: String      # "hookean" | "fenepm"
end

const NK        = 5000
const HK        = 0.25
const LUT_N     = 4000
const SHEAR_WI  = (1e-2, 1e4, 10)      # λ₀γ̇ min, max, points per decade

function grid_cases()
    cases = KmrCase[]
    for (block, drag, phi, spec) in (("A", "constant", 0.0, "rouse-scaling"),
                                     ("B", "c2d2",     0.0, "blob"),
                                     ("C", "c2d2",     1.0, "blob"))
        for Nm in (1, 10, 100), force in ("hookean", "fenepm")
            id = @sprintf("%s_%s_phi%g_Nm%d_%s", block, drag, phi, Nm, force)
            push!(cases, KmrCase(id, block, drag, phi, Nm, spec, force))
        end
    end
    return cases
end

